// Writes each Worker's wrangler.jsonc from the household config and the resource ids. No dependencies.
//   node setup/wrangler-config.mjs           write apps/*/wrangler.jsonc
//   node setup/wrangler-config.mjs --check   exit 1 if a committed file is out of date
// Reads household.config.json and setup/resources.json; falls back to the example files next to them, so a fresh
// copy of the template renders with placeholders. Never edit a wrangler.jsonc by hand: change the inputs, run this.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseHousehold, resourceName } from "../packages/core/src/household.ts";
import { routePatterns } from "../apps/gateway/src/services.ts";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const COMPATIBILITY_DATE = "2026-10-28";

const readJson = (p) => JSON.parse(readFileSync(p, "utf8"));
const firstOf = (...paths) => paths.find((p) => existsSync(p));

/** The inputs as they are on disk: the real files when they exist, else the examples. */
export function loadInputs(root = ROOT) {
  const config = readJson(firstOf(join(root, "household.config.json"), join(root, "household.config.example.json")));
  const resources = readJson(firstOf(join(root, "setup/resources.json"), join(root, "setup/resources.example.json")));
  return { config, resources };
}

/** Problems with the resource ids, in plain words. Empty = fine. */
export function resourceProblems(r) {
  const out = [];
  if (typeof r?.accessTeam !== "string" || !/^[a-z0-9-]+$/.test(r.accessTeam)) out.push("accessTeam: the Zero Trust team name (the first part of <team>.cloudflareaccess.com)");
  if (typeof r?.accessAud !== "string" || !/^[0-9a-f]{64}$/.test(r.accessAud)) out.push("accessAud: the 64-character AUD tag of the Access application");
  if (typeof r?.gateway?.d1DatabaseId !== "string" || !/^[0-9a-f-]{36}$/.test(r.gateway.d1DatabaseId)) out.push("gateway.d1DatabaseId: the id of the gateway's D1 database");
  if (typeof r?.gateway?.kvNamespaceId !== "string" || !/^[0-9a-f]{32}$/.test(r.gateway.kvNamespaceId)) out.push("gateway.kvNamespaceId: the id of the gateway's KV namespace");
  return out;
}

const HEADER = (what) => `// GENERATED by setup/wrangler-config.mjs from household.config.json and setup/resources.json. Do not edit by hand.\n// ${what}\n`;

/** The config text the Workers get as the HOUSEHOLD var: the parsed config, defaults filled in. */
const householdVar = (h) => JSON.stringify(h);

export function shellConfig(h, r) {
  return {
    $schema: "node_modules/wrangler/config-schema.json",
    name: resourceName(h, "shell"),
    main: "src/index.ts",
    compatibility_date: COMPATIBILITY_DATE,
    compatibility_flags: ["global_fetch_strictly_public"],
    workers_dev: false,
    preview_urls: false,
    routes: [{ pattern: h.domain, custom_domain: true }],
    assets: { directory: "public", binding: "ASSETS", run_worker_first: true, not_found_handling: "single-page-application" },
    build: { command: "npm run build" },
    observability: { enabled: true },
    vars: { HOUSEHOLD: householdVar(h), ACCESS_TEAM: r.accessTeam, ACCESS_AUD: r.accessAud },
  };
}

export function gatewayConfig(h, r) {
  return {
    $schema: "node_modules/wrangler/config-schema.json",
    name: resourceName(h, "gateway"),
    main: "src/index.ts",
    compatibility_date: COMPATIBILITY_DATE,
    compatibility_flags: ["nodejs_compat", "global_fetch_strictly_public"],
    workers_dev: false,
    preview_urls: false,
    routes: routePatterns(h.domain),
    observability: { enabled: true },
    d1_databases: [{ binding: "DB", database_name: resourceName(h, "gateway"), database_id: r.gateway.d1DatabaseId, migrations_dir: "migrations" }],
    kv_namespaces: [{ binding: "OAUTH_KV", id: r.gateway.kvNamespaceId }],
    vars: { HOUSEHOLD: householdVar(h), ACCESS_TEAM: r.accessTeam, ACCESS_AUD: r.accessAud },
    triggers: { crons: ["30 3 * * *"] },
  };
}

/** { path: text } for every wrangler.jsonc. Throws with every problem listed when an input is wrong. */
export function render({ config, resources }) {
  const h = parseHousehold(config);
  const problems = resourceProblems(resources);
  if (problems.length) throw new Error(`setup/resources.json: ${problems.join("; ")}`);
  const file = (what, obj) => HEADER(what) + JSON.stringify(obj, null, 2) + "\n";
  return {
    "apps/shell/wrangler.jsonc": file("The dashboard Worker: the household's domain, the built UI as static assets.", shellConfig(h, resources)),
    "apps/gateway/wrangler.jsonc": file("The MCP gateway Worker: routes on the same domain that win over the dashboard for the MCP and OAuth paths.", gatewayConfig(h, resources)),
  };
}

/** Paths whose file on disk differs from what the inputs render to. */
export function outOfDate(root = ROOT) {
  const files = render(loadInputs(root));
  return Object.entries(files).filter(([p, text]) => !existsSync(join(root, p)) || readFileSync(join(root, p), "utf8") !== text).map(([p]) => p);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    if (process.argv.includes("--check")) {
      const stale = outOfDate();
      if (stale.length) { console.error(`out of date: ${stale.join(", ")}\nrun: node setup/wrangler-config.mjs`); process.exit(1); }
      console.log("wrangler configs are up to date");
    } else {
      for (const [p, text] of Object.entries(render(loadInputs()))) { writeFileSync(join(ROOT, p), text); console.log(`wrote ${p}`); }
    }
  } catch (e) {
    console.error(e.message);
    process.exit(1);
  }
}
